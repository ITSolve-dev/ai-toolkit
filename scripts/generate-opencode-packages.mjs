import { readFile, readdir, writeFile } from "node:fs/promises"
import { fileURLToPath } from "node:url"

const root = new URL("../", import.meta.url)
const modules = [
  "anti-sycophancy",
  "domain-driven-guide",
  "llm-wiki",
  "spartan",
  "spec-driven-guide",
]
const dependencies = { "@opencode/plugin": "2.4.1", yaml: "^2.8.0" }
const check = process.argv.includes("--check")
const json = (value) => JSON.stringify(value, null, 2) + "\n"

async function output(path, content) {
  const url = new URL(path, root)
  if (check) {
    if ((await readFile(url, "utf8")).replaceAll("\r\n", "\n") !== content) {
      throw new Error(`Stale generated file: ${fileURLToPath(url)}`)
    }
  } else {
    await writeFile(url, content)
  }
}

function manifest(name, version, files) {
  return { name, version, type: "module", exports: { ".": "./server.ts" }, files, dependencies }
}

const inventories = new Map()
const counts = new Map()
for (const name of modules) {
  const entries = await readdir(new URL(`plugins/${name}/skills/`, root), { withFileTypes: true })
  const skills = entries.filter((entry) => entry.isDirectory()).map((entry) => entry.name).sort()
  inventories.set(name, skills)
  for (const skill of skills) counts.set(skill, (counts.get(skill) ?? 0) + 1)
}

const marker = "// Generated by scripts/generate-opencode-packages.mjs; do not edit.\n"
for (const [name, skills] of inventories) {
  const dir = `plugins/${name}/`
  const { version } = JSON.parse(await readFile(new URL(`${dir}plugin.json`, root), "utf8"))
  const ids = Object.fromEntries(skills.map((skill) => [
    skill, counts.get(skill) > 1 ? `${name}-${skill}` : skill,
  ]))
  const entries = await readdir(new URL(dir, root), { withFileTypes: true })
  const files = [
    "server.ts", "plugin.json",
    ...["agents", "assets", "hooks", "knowledge", "references", "skills", "workflows"].filter((key) =>
      entries.some((entry) => entry.isDirectory() && entry.name === key)),
  ]
  await output(`${dir}package.json`, json(manifest(`@itsolve-dev/opencode-${name}`, version, files)))
  await output(`${dir}server.ts`, marker + `import { readFile } from "node:fs/promises"
import { fileURLToPath } from "node:url"
import { Plugin, Skill } from "@opencode/plugin"
import { parse } from "yaml"

const skills = ${json(ids)}
export async function register(ctx: Pick<Plugin.Context, "skill">) {
  const definitions = await Promise.all(Object.entries(skills).map(async ([directory, id]) => {
    const path = fileURLToPath(new URL(\`./skills/\${directory}/SKILL.md\`, import.meta.url))
    const source = await readFile(path, "utf8")
    const match = /^---\\r?\\n([\\s\\S]*?)\\r?\\n---\\r?\\n([\\s\\S]*)$/.exec(source)
    if (!match) throw new Error(\`Missing YAML frontmatter: \${path}\`)
    const [, frontmatter, content] = match
    const { name, description } = parse(frontmatter) ?? {}
    if (typeof name !== "string" || typeof description !== "string") {
      throw new Error(\`Expected name and description in \${path}\`)
    }
    return {
      id: Skill.ID.make(id),
      name: Skill.Name.make(name),
      description,
      path: Skill.Info.fields.path.make(path),
      content,
    }
  }))
  await ctx.skill.transform((editor) => {
    for (const skill of definitions) {
      if (!editor.get(skill.id)) editor.add(skill)
    }
  })
}

export default Plugin.define({ id: "itsolve.${name}", setup: register })
`)
}

await output("server.ts", marker + `import { Plugin } from "@opencode/plugin"
${modules.map((name, index) => `import { register as register${index} } from "./plugins/${name}/server.ts"`).join("\n")}

export default Plugin.define({
  id: "itsolve.ai-toolkit",
  async setup(ctx) {
${modules.map((_, index) => `    await register${index}(ctx)`).join("\n")}
  },
})
`)
await output("package.json", json(manifest(
  "@itsolve-dev/opencode-ai-toolkit",
  "0.1.0",
  ["server.ts", ...modules.map((name) => `plugins/${name}`)],
)))
